import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import handler from '../worker/index.js';
const origin='https://salvo.example';
const secret='private_test_only_key',env={IMAGEKIT_PRIVATE_KEY:secret,IMAGEKIT_PUBLIC_KEY:'public_test_key'};
const req=(path,options={})=>new Request(origin+path,options);
const identity={'oai-authenticated-user-id':'test-owner'};
assert.equal((await handler.fetch(req('/api/config'),env)).status,401,'API requires authenticated identity');
assert.equal((await handler.fetch(req('/api/config',{headers:identity}),{})).status,200);
assert.equal((await handler.fetch(req('/api/upload-auth',{method:'POST',headers:identity}),env)).status,403,'Origin/custom header required');
const headers={...identity,Origin:origin,'X-Salvo-Request':'upload'};
const response=await handler.fetch(req('/api/upload-auth',{method:'POST',headers}),env);
const auth=await response.json();assert.equal(response.status,200);
assert.equal(auth.signature,createHmac('sha1',secret).update(auth.token+auth.expire).digest('hex'));
assert.ok(auth.expire> Date.now()/1000&&auth.expire<Date.now()/1000+301);
const auth2=await(await handler.fetch(req('/api/upload-auth',{method:'POST',headers}),env)).json();
assert.notEqual(auth.token,auth2.token,'Every upload gets a unique token');
assert.equal((await handler.fetch(req('/api/upload-auth',{method:'POST',headers:{...headers,Origin:'https://wrong.example'}}),env)).status,403);
const html=await(await handler.fetch(req('/'),env)).text();assert.ok(!html.includes(secret));assert.ok(!html.includes('local-handoff'));assert.ok(html.includes('Share your photos &amp; videos'));
assert.ok(!html.includes('<select'));
const library=await(await handler.fetch(req('/library'),env)).text();assert.ok(library.includes('Search media'));assert.ok(!library.includes(secret));
const originalFetch=globalThis.fetch;
globalThis.fetch=async(url)=>{url=new URL(url);assert.equal(url.searchParams.get('searchQuery'),'"tags" IN ["upload-test"]');return Response.json([{filePath:'/salvo-soccer/test-uploads/club/a.png',name:'a.png'},{filePath:'/unrelated/a.png',name:'unrelated'}])};
const list=await(await handler.fetch(req('/api/files',{headers:identity}),env)).json();assert.equal(list.length,1);assert.equal(list[0].name,'a.png');
globalThis.fetch=originalFetch;
console.log('Passed: identity, setup state, origin checks, HMAC signature, five-minute expiry, token uniqueness, secret isolation, nested-folder listing.');
